-- KORACI 4 I 5: zvjezdasta shema i vremenska dimenzija (PostgreSQL).
-- Pokrenuti u istoj bazi nakon skripti 01 i 02.
-- Tablice skladista su u zasebnoj shemi dw.
-- Ova skripta kreira strukturu. Punjenje dimenzija i cinjenica slijedi kasnije.
-- Jedan red factdolaznost = jedan upis clana na jednom odrzanom treningu.
-- Izvor: dolaznost, upis, trening, termin i grupa.
-- Pokrenuti jednom. Postojece tablice se ne brisu niti mijenjaju.

BEGIN;

CREATE SCHEMA IF NOT EXISTS dw;

CREATE TABLE dw.dimdate (
    datekey INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    datum DATE NOT NULL UNIQUE,
    dan SMALLINT NOT NULL CHECK (dan BETWEEN 1 AND 31),
    mjesec SMALLINT NOT NULL CHECK (mjesec BETWEEN 1 AND 12),
    naziv_mjeseca VARCHAR(15) NOT NULL,
    kvartal SMALLINT NOT NULL CHECK (kvartal BETWEEN 1 AND 4),
    godina SMALLINT NOT NULL CHECK (godina > 0),
    dan_u_tjednu SMALLINT NOT NULL CHECK (dan_u_tjednu BETWEEN 1 AND 7),
    naziv_dana VARCHAR(15) NOT NULL,
    -- ISO oznaka: ponedjeljak = 1, nedjelja = 7.
    CHECK (dan = EXTRACT(DAY FROM datum)),
    CHECK (mjesec = EXTRACT(MONTH FROM datum)),
    CHECK (kvartal = EXTRACT(QUARTER FROM datum)),
    CHECK (godina = EXTRACT(YEAR FROM datum)),
    CHECK (dan_u_tjednu = EXTRACT(ISODOW FROM datum))
);

CREATE TABLE dw.dimclan (
    clankey INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clan_id INTEGER NOT NULL UNIQUE,
    ime VARCHAR(50) NOT NULL,
    prezime VARCHAR(50) NOT NULL,
    datum_rodenja DATE NOT NULL,
    email VARCHAR(100) NOT NULL,
    datum_uclanjenja DATE NOT NULL
);

CREATE TABLE dw.dimgrupa (
    grupakey INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupa_id INTEGER NOT NULL UNIQUE,
    naziv VARCHAR(80) NOT NULL,
    razina VARCHAR(30) NOT NULL
        CHECK (razina IN ('pocetna', 'srednja', 'natjecateljska')),
    sezona_id INTEGER NOT NULL,
    naziv_sezone VARCHAR(20) NOT NULL,
    datum_pocetka_sezone DATE NOT NULL,
    datum_zavrsetka_sezone DATE NOT NULL,
    bazen_id INTEGER NOT NULL,
    naziv_bazena VARCHAR(100) NOT NULL,
    adresa_bazena VARCHAR(100) NOT NULL,
    broj_staza INTEGER NOT NULL CHECK (broj_staza > 0),
    CHECK (datum_zavrsetka_sezone > datum_pocetka_sezone)
);

CREATE TABLE dw.dimtrener (
    trenerkey INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trener_id INTEGER NOT NULL UNIQUE,
    ime VARCHAR(50) NOT NULL,
    prezime VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL
);

CREATE TABLE dw.factdolaznost (
    dolaznostkey INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dolaznost_id INTEGER NOT NULL UNIQUE,
    upis_id INTEGER NOT NULL,
    trening_id INTEGER NOT NULL,
    datekey INTEGER NOT NULL REFERENCES dw.dimdate(datekey),
    clankey INTEGER NOT NULL REFERENCES dw.dimclan(clankey),
    grupakey INTEGER NOT NULL REFERENCES dw.dimgrupa(grupakey),
    trenerkey INTEGER NOT NULL REFERENCES dw.dimtrener(trenerkey),
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('prisutan', 'odsutan', 'opravdano')),
    broj_evidencija SMALLINT NOT NULL DEFAULT 1 CHECK (broj_evidencija = 1),
    broj_dolazaka SMALLINT NOT NULL CHECK (broj_dolazaka IN (0, 1)),
    broj_izostanaka SMALLINT NOT NULL CHECK (broj_izostanaka IN (0, 1)),
    UNIQUE (upis_id, trening_id),
    CHECK (broj_dolazaka + broj_izostanaka = broj_evidencija),
    CHECK (
        (status = 'prisutan' AND broj_dolazaka = 1 AND broj_izostanaka = 0)
        OR (status IN ('odsutan', 'opravdano')
            AND broj_dolazaka = 0 AND broj_izostanaka = 1)
    )
);

COMMIT;

-- Provjera nakon izvrsavanja: ocekuje se pet tablica.
SELECT table_schema, table_name
FROM information_schema.tables
WHERE table_schema = 'dw' AND table_type = 'BASE TABLE'
ORDER BY table_name;
